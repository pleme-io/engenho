//! engenho-control-types — the central types of engenho's control plane.
//!
//! Everything a transport, the CLI, or the MCP server needs to speak the
//! control API is DERIVED at build time from the one authored spec,
//! `spec/engenho-control.openapi.yaml` (see `build.rs` and
//! `docs/CONTROL-PLANE.md`):
//!
//! * [`types`] — every `components.schemas` entry (typify).
//! * [`OperationId`] + [`CATALOG`] — every operation with its method, path,
//!   authority tier, confirm gate and CLI spelling, from the spec's
//!   `x-engenho-*` extensions.
//! * [`ops`] — one marker type and one typed `…Request` per operation, each
//!   [`Operation`] binding marker → request → response, and the
//!   [`EngenhoControl`] trait with one method per operation.
//!
//! Hand-written here: only the glue that is not a schema — the principal,
//! the error type, the HTTP rendering helpers, and the catalog row types.

