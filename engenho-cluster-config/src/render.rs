impl ClusterConfig {
    /// Render the YAML body for `/etc/rancher/k3s/config.yaml`.
    #[must_use]
    pub fn render_k3s_config_yaml(&self) -> String {
        let net = &self.network;
        let mut sans = net.tls_sans.clone();
        sans.push(self.node_ip.to_string());
        sans.sort();
        sans.dedup();
        let sans_yaml = sans
            .iter()
            .map(|s| format!("  - {s}"))
            .collect::<Vec<_>>()
            .join("\n");

        // NOTE: cluster-cidr / service-cidr / cluster-dns are NOT
        // emitted here — the nixos-k3s-vm consumer sets them via
        // `services.blackmatter.k3s.{clusterCIDR,serviceCIDR,clusterDNS}`
        // (cmdline flags). Emitting them here ALSO would cause k3s to
        // see both values as a dual-stack list (config.yaml + cmdline
        // merged), failing with "must be of different IP family" when
        // dual_stack=false. dual-stack is rendered via cmdline overrides
        // by the consumer when dual_stack=true.
        let mut out = formatdoc! {"
            # Generated by engenho-cluster-config for {name}
            node-name: {name}
            service-node-port-range: {nps_start}-{nps_end}
            tls-san:
            {sans}
            ",
            name         = self.cluster_name,
            nps_start    = net.node_port_range.start,
            nps_end      = net.node_port_range.end,
            sans         = sans_yaml,
        };
        let _ = net.cluster_dns; // documented above: consumer-owned
        if let Some(mtu) = net.mtu {
            out.push_str(&format!("flannel-iface-mtu: {mtu}\n"));
        }
        if let Some(adv) = net.advertise_address {
            out.push_str(&format!("advertise-address: {adv}\n"));
        }
        if let Some(bind) = net.bind_address {
            out.push_str(&format!("bind-address: {bind}\n"));
        }
        out
    }

    /// Render the additional cmdline args appended after `k3s server`.
    /// These cover knobs not expressible (or not idiomatic) in
    /// `config.yaml`.
    #[must_use]
    pub fn render_k3s_server_args(&self) -> Vec<String> {
        let net = &self.network;
        let mut args: Vec<String> = Vec::new();

        // Disabled components — combine the explicit list with auto-
        // derivations from CNI / ingress / LB / DNS choices.
        let mut disable: Vec<K3sComponent> = net.disable_components.clone();
        // Non-default CNI ⇒ disable flannel.
        if !matches!(net.cni, CniChoice::Flannel) {
            // k3s exposes flannel-disable via `--flannel-backend=none`,
            // see below. No K3sComponent for it.
        }
        // Non-default ingress ⇒ disable traefik.
        if !matches!(net.ingress, IngressChoice::Traefik) {
            disable.push(K3sComponent::Traefik);
        }
        // Non-default LB ⇒ disable servicelb.
        if !matches!(net.load_balancer, LoadBalancerChoice::Servicelb) {
            disable.push(K3sComponent::Servicelb);
        }
        // External DNS ⇒ disable coredns.
        if matches!(net.dns, DnsChoice::External) {
            disable.push(K3sComponent::Coredns);
        }
        // network-policy=delegated|disabled ⇒ disable built-in controller.
        match net.network_policy.enforce {
            NetworkPolicyEnforce::Enabled => {}
            NetworkPolicyEnforce::Disabled | NetworkPolicyEnforce::Delegated => {
                disable.push(K3sComponent::NetworkPolicy);
            }
        }
        // kube-proxy disabled ⇒ disable
        if net.kube_proxy.disabled {
            disable.push(K3sComponent::KubeProxy);
        }
        disable.sort_by_key(|c| c.as_k3s_disable());
        disable.dedup();
        for c in &disable {
            args.push(format!("--disable={}", c.as_k3s_disable()));
        }

        // CNI selection.
        match net.cni {
            CniChoice::Flannel => {
                if let Some(b) = net.cni_backend {
                    args.push(format!("--flannel-backend={}", flannel_backend(b)));
                }
            }
            CniChoice::Calico | CniChoice::Cilium => {
                args.push("--flannel-backend=none".into());
                args.push("--disable-network-policy".into());
                args.push("--disable-kube-proxy".into());
            }
            CniChoice::None => {
                args.push("--flannel-backend=none".into());
                args.push("--disable-network-policy".into());
                args.push("--disable-cni".into());
            }
        }

        // kube-proxy mode (only when not disabled).
        if !net.kube_proxy.disabled
            && !matches!(net.kube_proxy.mode, KubeProxyMode::Iptables)
        {
            args.push(format!(
                "--kube-proxy-arg=proxy-mode={}",
                kube_proxy_mode(net.kube_proxy.mode)
            ));
        }

        args
    }

    /// Render the bootstrap manifests dropped into
    /// `/var/lib/rancher/k3s/server/manifests/`. k3s auto-applies the
    /// directory at startup. Order doesn't matter for k3s' apply loop
    /// (it's idempotent + retries), but the renderer emits a stable
    /// order keyed by filename for diff-stability.
    #[must_use]
    pub fn render_bootstrap_manifests(&self) -> Vec<Manifest> {
        let mut out: Vec<Manifest> = Vec::new();
        let net = &self.network;

        // CNI install manifests.
        match net.cni {
            CniChoice::Flannel | CniChoice::None => {} // built-in or operator-provided
            CniChoice::Calico  => out.push(calico_manifest()),
            CniChoice::Cilium  => out.push(cilium_manifest(net.kube_proxy.disabled)),
        }

        // Ingress controller manifests (only when non-default).
        match net.ingress {
            IngressChoice::Traefik     => {} // k3s default
            IngressChoice::Nginx       => out.push(nginx_ingress_manifest()),
            IngressChoice::Contour     => out.push(contour_manifest()),
            IngressChoice::GatewayApi  => out.push(gateway_api_manifest()),
            IngressChoice::None        => {} // operator-provided
        }

        // LoadBalancer manifests (only when non-default).
        match net.load_balancer {
            LoadBalancerChoice::Servicelb => {} // k3s default
            LoadBalancerChoice::Metallb   => out.push(metallb_manifest()),
            LoadBalancerChoice::KubeVip   => out.push(kubevip_manifest()),
            LoadBalancerChoice::None      => {} // operator-provided
        }

        // DNS overlay (nodelocal-dns when chosen).
        if matches!(net.dns, DnsChoice::NodelocalDns) {
            out.push(nodelocal_dns_manifest(net.cluster_dns));
        }

        // GitOps bootstrap.
        if self.bootstrap.fluxcd.enable {
            out.push(fluxcd_install_manifest(&self.bootstrap.fluxcd));
            if self.bootstrap.fluxcd.source.is_some() {
                out.push(fluxcd_source_manifest(&self.cluster_name, &self.bootstrap.fluxcd));
            }
        }
        if self.bootstrap.argocd.enable {
            out.push(argocd_install_manifest(&self.bootstrap.argocd));
            if self.bootstrap.argocd.source.is_some() {
                out.push(argocd_application_manifest(&self.cluster_name, &self.bootstrap.argocd));
            }
        }

        out.sort_by(|a, b| a.filename.cmp(&b.filename));
        out
    }
}

fn flannel_backend(b: FlannelBackend) -> &'static str {
    match b {
        FlannelBackend::Vxlan            => "vxlan",
        FlannelBackend::HostGw           => "host-gw",
        FlannelBackend::WireguardNative  => "wireguard-native",
        FlannelBackend::WireguardLegacy  => "wireguard",
        FlannelBackend::Ipsec            => "ipsec",
    }
}

fn kube_proxy_mode(m: KubeProxyMode) -> &'static str {
    match m {
        KubeProxyMode::Iptables => "iptables",
        KubeProxyMode::Ipvs     => "ipvs",
        KubeProxyMode::Nftables => "nftables",
    }
}

// ─────────────────────────────────────────────────────────────────────
// Manifest emitters — minimal HelmChart CRDs that k3s' helm-controller
// applies. Each manifest is one document; consumers can override
// `valuesContent` via downstream patches.
// ─────────────────────────────────────────────────────────────────────

fn calico_manifest() -> Manifest {
    Manifest::new("calico.yaml", formatdoc! {"
        apiVersion: helm.cattle.io/v1
        kind: HelmChart
        metadata:
          name: calico
          namespace: kube-system
        spec:
          repo: https://docs.tigera.io/calico/charts
          chart: tigera-operator
          targetNamespace: tigera-operator
          createNamespace: true
    "})
}

fn cilium_manifest(replace_kube_proxy: bool) -> Manifest {
    let replace = if replace_kube_proxy { "true" } else { "false" };
    Manifest::new("cilium.yaml", formatdoc! {"
        apiVersion: helm.cattle.io/v1
        kind: HelmChart
        metadata:
          name: cilium
          namespace: kube-system
        spec:
          repo: https://helm.cilium.io
          chart: cilium
          targetNamespace: kube-system
          valuesContent: |-
            kubeProxyReplacement: {replace}
            k8sServiceHost: 127.0.0.1
            k8sServicePort: 6443
    ", replace = replace})
}

