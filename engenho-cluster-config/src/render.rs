fn argocd_application_manifest(cluster_name: &str, cfg: &ArgocdBootstrap) -> Manifest {
    let source = cfg.source.as_ref().expect("validate() guarantees Some when enable=true");
    let target_rev = cfg.target_revision.clone().unwrap_or_else(|| source.branch.clone());
    Manifest::new("argocd-application.yaml", formatdoc! {"
        apiVersion: argoproj.io/v1alpha1
        kind: Application
        metadata:
          name: {name}-root
          namespace: argocd
        spec:
          project: default
          source:
            repoURL: {url}
            targetRevision: {target_rev}
            path: {path}
          destination:
            server: https://kubernetes.default.svc
            namespace: argocd
          syncPolicy:
            automated:
              prune: true
              selfHeal: true
    ",
        name       = cluster_name,
        url        = source.url,
        target_rev = target_rev,
        path       = cfg.path,
    })
}

fn render_gitops_secret_placeholder(cluster_name: &str, kind: SecretKind) -> String {
    // The actual credential value is materialized by sops-nix at
    // activation time. The nixos-k3s-vm consumer is responsible for
    // declaring the matching `sops.secrets.<sops_key>` + dropping the
    // populated YAML in place of this placeholder.
    let (secret_type, data_key) = match kind {
        SecretKind::HttpsToken => ("kubernetes.io/basic-auth", "password"),
        SecretKind::SshKey     => ("kubernetes.io/ssh-auth",   "identity"),
    };
    formatdoc! {"
        ---
        apiVersion: v1
        kind: Secret
        type: {secret_type}
        metadata:
          name: {name}-gitops-auth
          namespace: flux-system
        stringData:
          username: oauth2  # ignored for ssh-auth
          {data_key}: REPLACED-BY-SOPS-NIX-ACTIVATION
    ",
        secret_type = secret_type,
        name        = cluster_name,
        data_key    = data_key,
    }
}
