//! Renderers — typed config → k3s flags / config.yaml / bootstrap manifests.
//!
//! Three load-bearing render paths:
//!
//! 1. [`ClusterConfig::render_k3s_config_yaml`] — emits the YAML k3s
//!    consumes from `/etc/rancher/k3s/config.yaml`. Covers most knobs
//!    (CIDRs, dns, node-port-range, tls-sans, mtu, ipv6, addresses).
//!
//! 2. [`ClusterConfig::render_k3s_server_args`] — extra `--flag=value`
//!    args appended to the k3s server command. Covers `--disable=…`,
//!    `--flannel-backend=…`, `--kube-proxy-arg=…`, `--disable-kube-proxy`,
//!    `--disable-network-policy`, `--cluster-init`.
//!
//! 3. [`ClusterConfig::render_bootstrap_manifests`] — emits CNI install
//!    manifests, ingress controller manifests, LB manifests, DNS overlay
//!    manifests, FluxCD install, ArgoCD install. Each manifest is
//!    keyed by filename for `/var/lib/rancher/k3s/server/manifests/`.

use indoc::formatdoc;

