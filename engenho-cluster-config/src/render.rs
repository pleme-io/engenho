fn fluxcd_source_manifest(cluster_name: &str, cfg: &FluxcdBootstrap) -> Manifest {
    let source = cfg.source.as_ref().expect("validate() guarantees Some when enable=true");
    let secret_ref = if source.auth.is_some() {
        formatdoc! {"
              secretRef:
                name: {name}
        ", name = format!("{cluster_name}-gitops-auth")}
    } else {
        String::new()
    };
    let body = formatdoc! {"
        ---
        apiVersion: source.toolkit.fluxcd.io/v1
        kind: GitRepository
        metadata:
          name: {name}
          namespace: flux-system
        spec:
          interval: {interval}
          url: {url}
          ref:
            branch: {branch}
        {secret_ref}---
        apiVersion: kustomize.toolkit.fluxcd.io/v1
        kind: Kustomization
        metadata:
          name: {name}
          namespace: flux-system
        spec:
          interval: {interval}
          path: {path}
          prune: true
          sourceRef:
            kind: GitRepository
            name: {name}
        ",
        name     = cluster_name,
        interval = cfg.interval,
        url      = source.url,
        branch   = source.branch,
        path     = cfg.path,
        secret_ref = secret_ref,
    };
    let mut m = Manifest::new("flux-system-source.yaml", body);
    if let Some(auth) = &source.auth {
        m.body.push_str(&render_gitops_secret_placeholder(cluster_name, auth.kind));
    }
    m
}

